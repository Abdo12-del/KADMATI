/**
 * Generates `src/lib/iconSet.ts` — a static map of exactly the icons the picker offers.
 *
 * Why this exists: `iconLibrary.ts` used to do `import * as lucide from 'lucide'` and then
 * `lucide[pascalCase(name)]`. A bundler cannot know which of lucide's 1861 exports a dynamic
 * key will hit, so it kept all of them — measured: 453 kB raw / 100 kB gzip, a quarter of the
 * entry chunk, for ~165 icons we actually show.
 *
 * Emitting explicit named imports makes the graph static again, so tree-shaking drops the
 * other ~1700 icons. Run this after editing `src/lib/iconCatalog.ts`:
 *
 *   npm run icons:generate
 */
import fs from 'node:fs'
import path from 'node:path'
import esbuild from 'esbuild'

const ROOT = process.cwd()
const OUT = 'src/lib/iconSet.ts'

/* ---------------------------------------------------------------- catalog */

// The catalog is TypeScript; bundle it to a throwaway module rather than parsing it by regex.
await esbuild.build({
  entryPoints: ['src/lib/iconCatalog.ts'],
  bundle: true,
  platform: 'neutral',
  format: 'esm',
  outfile: '.tmp-verify/icon-catalog.mjs',
  logLevel: 'warning',
})
const { ALL_ICONS } = await import(path.resolve(ROOT, '.tmp-verify/icon-catalog.mjs'))

/** Same rule the runtime lookup used, so an icon's id is stable across the change. */
function pascalCase(name) {
  return name
    .replace(/[^a-zA-Z0-9]/g, ' ')
    .split(' ')
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('')
}

/* ---------------------------------------------------------------- validate against lucide */

// lucide ships one big .d.ts with every export; that is the cheapest authoritative name list.
const dts = fs.readFileSync(path.join(ROOT, 'node_modules/lucide/dist/lucide.d.ts'), 'utf8')
const exported = new Set()
for (const m of dts.matchAll(/^declare const ([A-Za-z0-9_]+):/gm)) exported.add(m[1])

const resolved = []
const missing = []
for (const name of ALL_ICONS) {
  const key = pascalCase(name)
  if (exported.has(key)) resolved.push([name, key])
  else missing.push(`${name} → ${key}`)
}

if (missing.length) {
  console.warn(`\n⚠ ${missing.length} catalog entries are not lucide exports and will render the placeholder:`)
  for (const m of missing) console.warn(`   ${m}`)
  console.warn('')
}

/* ---------------------------------------------------------------- emit */

const body = resolved
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, key]) => `  '${name}': ${key},`)
  .join('\n')

const file = `/**
 * GENERATED by scripts/gen-icon-set.mjs — do not edit by hand.
 * Run \`npm run icons:generate\` after changing src/lib/iconCatalog.ts.
 *
 * ${resolved.length} icons, imported by name so the bundler can drop the other ~1700 that
 * ship with lucide. A namespace import here would put the entire set in the entry chunk.
 */
import {
${resolved
  .sort(([, a], [, b]) => a.localeCompare(b))
  .map(([, key]) => `  ${key},`)
  .join('\n')}
} from 'lucide'

export type IconNode = [tag: string, attrs: Record<string, string | number>][]

/** kebab-case lucide id → vector node tree. */
export const ICON_NODES: Record<string, IconNode> = {
${body}
}
`

fs.writeFileSync(path.join(ROOT, OUT), file)
console.log(`icon set → ${OUT} (${resolved.length} icons${missing.length ? `, ${missing.length} missing` : ''})`)
